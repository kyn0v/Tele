import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from 'playwright';
import { previewPi, root } from './pi-preview.mjs';

const directory = await mkdtemp(join(tmpdir(), 'tele-chat-model-'));
const model = process.env.TELE_TEST_MODEL ?? 'github-copilot/gpt-6-luna';
const pi = previewPi({ directory, model, persist: true });
const output = `${root}.audit/chat`;
let browser;
let prompts = 0;
let deltas = 0;
let boardCalls = 0;
const models = new Set();
pi.observe(event => {
  if (event.type === 'agent_start') prompts++;
  if (event.type === 'message_update' && event.assistantMessageEvent?.type === 'text_delta') deltas++;
  if (event.type === 'tool_execution_start') { assert.equal(event.toolName, 'tele_board'); boardCalls++; }
  if (event.type === 'message_end' && event.message?.role === 'assistant') models.add(`${event.message.provider}/${event.message.model}`);
});
try {
  await mkdir(output, { recursive: true });
  await pi.command('get_state');
  const priorSettled = pi.wait(event => event.type === 'agent_settled', 180_000);
  await pi.command('prompt', { message: 'This is a disposable music preview. Remember our practice name is Copper Lantern and our cadence is Em, A, D. Do not use tools. Reply with the name and cadence, then eight short numbered practice tips (under 120 words total).' });
  await priorSettled;
  const previous = await pi.command('get_last_assistant_text');
  assert(previous.text?.includes('Copper Lantern'), 'Configured model produced the prior canary conversation');
  const invitation = await pi.attach();
  const origin = new URL(invitation).origin;
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  await page.addInitScript(() => { if (!localStorage.getItem('tele.locale')) localStorage.setItem('tele.locale', 'zh-CN'); });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(invitation).catch(() => { throw new Error('Preview pairing navigation failed'); });
  await page.waitForFunction(() => document.querySelector('.chat-panel')?.dataset.phase === 'idle');
  assert.equal(new URL(page.url()).hash, '', 'Pairing fragment erased');
  assert.match(await page.locator('.chat-history').textContent(), /Copper Lantern/);
  assert.equal(await page.evaluate(() => document.cookie), '', 'Pair cookie is HttpOnly');
  const stored = await page.evaluate(() => Object.entries(localStorage));
  assert(stored.every(([key]) => /^(tele\.locale|tele\.chat\.(binding:[a-z0-9-]+|dock|collapsed))$/.test(key)), 'Storage contains only approved nonsecret preferences/binding');
  const anonymous = await browser.newContext();
  const binding = await page.evaluate(() => localStorage.getItem('tele.chat.binding:preview'));
  assert.equal((await anonymous.request.get(`${origin}/api/chat/${binding}`)).status(), 401);
  await anonymous.close();
  await page.screenshot({ path: join(output, 'history.png') });
  await page.locator('#chat-input').fill('Draft survives docking 和弦');
  await page.locator('#chat-input').evaluate(input => { window.composerProof = input; });
  for (const dock of ['left', 'bottom', 'right']) {
    await page.getByLabel('对话面板位置').selectOption(dock);
    assert.equal(await page.locator('#chat-input').inputValue(), 'Draft survives docking 和弦');
    assert(await page.locator('#chat-input').evaluate(input => input === window.composerProof));
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await page.screenshot({ path: join(output, `${dock}.png`) });
  }
  await page.getByRole('button', { name: '收起', exact: true }).click();
  await page.getByRole('button', { name: '展开对话', exact: true }).click();
  assert.equal(await page.locator('#chat-input').inputValue(), 'Draft survives docking 和弦');
  await page.locator('#chat-input').dispatchEvent('keydown', { key: 'Enter', isComposing: true });
  assert.equal(prompts, 1, 'IME Enter does not submit');
  await page.locator('#chat-input').press('Shift+Enter');
  assert((await page.locator('#chat-input').inputValue()).includes('\n'));
  await page.evaluate(() => {
    window.chatChanges = [];
    const history = document.querySelector('.chat-history');
    new MutationObserver(() => {
      const text = history.textContent;
      if (document.querySelector('.chat-panel').dataset.phase === 'busy' && text !== window.chatChanges.at(-1)) window.chatChanges.push(text);
    }).observe(history, { subtree: true, childList: true, characterData: true });
  });
  const secondSettled = pi.wait(event => event.type === 'agent_settled', 180_000);
  await page.locator('#chat-input').fill('Use the practice name and three chords from our earlier conversation. Get the current board, then replace its title with that practice name and its groups with one group using those three chords in that order. Keep tempo 90. Use the board tool, not files. Then state the remembered name and cadence in two sentences.');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  await page.waitForFunction(() => ['busy', 'submitted'].includes(document.querySelector('.chat-panel')?.dataset.phase));
  await secondSettled;
  await page.waitForFunction(() => document.querySelector('.chat-panel')?.dataset.phase === 'idle');
  if (Number(await page.locator('body').getAttribute('data-revision')) < 2) {
    const { messages } = await pi.command('get_messages');
    const diagnostic = messages.filter(message => ['assistant', 'toolResult'].includes(message.role)).map(message => ({ role: message.role, stopReason: message.stopReason, text: message.content.filter(block => block.type === 'text').map(block => block.text).join('\n') }));
    await writeFile(join(output, 'model-diagnostic.json'), JSON.stringify({ prompts, boardCalls, diagnostic }, null, 2));
    await page.screenshot({ path: join(output, 'model-failure.png') });
    throw new Error('Model did not update board. See local sanitized preview diagnostic.');
  }
  const board = await (await fetch(`${origin}/api/boards/preview`)).json();
  assert.equal(board.content.title, 'Copper Lantern');
  assert.deepEqual(board.content.groups[0].chords, ['Em', 'A', 'D']);
  assert(boardCalls >= 2, 'Actual model get and put tool calls');
  assert(await page.locator('#chat-input').evaluate(input => input === window.composerProof), 'Board update preserves composer identity');
  assert.equal(await page.locator('#chat-input').inputValue(), '', 'Observed input clears matching draft');
  assert.match(await page.locator('.chat-history').textContent(), /tele_board · 完成/);
  const projection = await (await page.request.get(`${origin}/api/chat/${binding}`)).json();
  assert(projection.items.some(item => item.role === 'tool' && item.name === 'tele_board' && item.status === 'completed' && !('text' in item)), 'Generated tool status uses the semantic wire shape');
  assert(projection.notice === null || typeof projection.notice === 'string' && /^[a-z]+(?:-[a-z]+)+$/.test(projection.notice), 'Lifecycle feedback uses a stable code, not localized prose');
  const streamChanges = await page.evaluate(() => window.chatChanges.length);
  assert(streamChanges > 1, 'Browser observed multiple in-flight projection changes');
  await page.screenshot({ path: join(output, 'board-updated.png') });
  await page.locator('.chat-history').evaluate(history => { history.scrollTop = 0; });
  const scrollBefore = await page.locator('.chat-history').evaluate(history => history.scrollTop);
  const thirdSettled = pi.wait(event => event.type === 'agent_settled', 180_000);
  const streaming = pi.wait(event => event.type === 'message_update' && event.assistantMessageEvent?.type === 'text_delta', 180_000);
  await page.locator('#chat-input').fill('Name the cadence we just put on the board. Without tools, explain each of its three chords in about 250 words.');
  await page.getByRole('button', { name: '发送', exact: true }).click();
  await streaming;
  await page.waitForFunction(() => document.querySelector('.chat-panel')?.dataset.phase === 'busy');
  assert.equal(await page.locator('.chat-history').evaluate(history => history.scrollTop), scrollBefore, 'Streaming does not pull a reader away from earlier history');
  await page.getByRole('button', { name: '停止回复', exact: true }).click();
  const ended = await thirdSettled;
  assert(ended.aborted, 'Real model run aborted through browser');
  await page.waitForFunction(() => document.querySelector('.chat-panel')?.dataset.phase === 'idle');
  await page.getByLabel('对话面板位置').selectOption('left');
  await page.reload();
  await page.waitForFunction(() => document.querySelector('.chat-panel')?.dataset.phase === 'idle');
  assert.equal(await page.locator('body').getAttribute('data-chat-dock'), 'left');
  assert.match(await page.locator('.chat-history').textContent(), /Copper Lantern/);
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.screenshot({ path: join(output, 'mobile.png') });
  assert(await page.locator('#chat-input').isVisible());
  await page.getByRole('button', { name: '收起', exact: true }).click();
  await page.screenshot({ path: join(output, 'mobile-collapsed.png') });
  await page.reload();
  assert.equal(await page.locator('body').getAttribute('data-chat-collapsed'), 'true');
  const state = await pi.command('get_state');
  const persisted = await readFile(state.sessionFile, 'utf8');
  assert(persisted.includes('Copper Lantern'));
  assert(persisted.includes('tele_board'));
  assert(persisted.includes('expectedRevision'));
  assert(!persisted.includes('#chat='), 'Pairing secret never enters the Pi transcript');
  const declarations = persisted.split('\n').filter(Boolean).map(line => JSON.parse(line)).flatMap(entry => entry.message?.toolsAdded ?? []).map(tool => tool.name);
  assert(declarations.every(name => name === 'tele_board'), 'Only reviewed board tool was declared to the model');
  assert.equal(prompts, 3);
  await pi.command('prompt', { message: '/tele off' });
  await assert.rejects(fetch(`${origin}/api/capabilities`));
  assert.equal((await pi.command('get_state')).isStreaming, false);
  assert.deepEqual(errors, []);
  const report = { kind: 'Separate preview Pi, not the parent live session', requestedModel: model, observedModels: [...models], userPrompts: prompts, streamedTextDeltas: deltas, browserStreamChanges: streamChanges, actualBoardToolCalls: boardCalls, board: { revision: board.revision, title: board.content.title, chords: board.content.groups[0].chords }, persistentPiHistory: true, sameProcessContinuation: true, browserAbort: ended.aborted, auth: 'private cookie and fragment erasure observed; anonymous history rejected', layout: 'right/left/bottom, collapsed persistence, 390px mobile; composer identity, IME and reader scroll preserved', limitations: 'Preview only. Terminal permission dialogs remain terminal-owned. No transcript copied or published.' };
  await writeFile(join(output, 'model-browser.json'), JSON.stringify(report, null, 2));
  process.stdout.write(`${JSON.stringify(report, null, 2)}\nArtifacts: ${output}\n`);
} finally { await browser?.close(); await pi.close(); await rm(directory, { recursive: true, force: true }); }
